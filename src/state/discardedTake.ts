import type { ClipVersion, SongIdea } from "../types";
import { trashRecorderTake } from "../services/managedMedia";
import { buildDefaultIdeaTitle } from "../domain/titleNaming";
import { genId } from "../utils";
import { captureDeletedTakes } from "./recentlyDeleted";
import { useStore } from "./useStore";

/** Shorter than this is a false start: Discard and Redo let it go (03-9). */
export const KEEP_DISCARDED_TAKE_MIN_MS = 5_000;

/** Where the take was headed when it was discarded, read at the moment of Discard. */
export type DiscardedTakeContext = {
    workspaceId: string | null;
    collectionId: string | null;
    /** The sketch (or clip idea) the take was being recorded into, if any. */
    ideaId: string | null;
    ideaTitle: string;
    durationMs: number;
};

/**
 * Discard and Redo in the recorder used to delete the take for good, behind one
 * dialog where the two answers sit side by side (03-9). A take longer than a false
 * start now waits in Recently deleted: its file in the trash, a record that restores
 * it into the sketch it was for, or as a clip where it was headed. Returns the
 * record ids (empty when nothing was kept, and the caller deletes the file).
 */
export async function keepDiscardedTake(fileUri: string, context: DiscardedTakeContext): Promise<string[]> {
    if (context.durationMs < KEEP_DISCARDED_TAKE_MIN_MS || !context.workspaceId) return [];
    const home = await trashRecorderTake(fileUri);
    if (!home) return [];
    const now = Date.now();
    const clip: ClipVersion = {
        id: genId("clip"),
        title: buildDefaultIdeaTitle(now),
        isTitleAutoGenerated: true,
        notes: "",
        createdAt: now,
        isPrimary: false,
        audioUri: home,
        durationMs: context.durationMs,
    };
    const target = {
        id: context.ideaId ?? genId("idea"),
        title: context.ideaTitle,
        collectionId: context.collectionId ?? "",
        clips: [],
    } as unknown as SongIdea;
    const state = useStore.getState();
    const kept = captureDeletedTakes(state, context.workspaceId, target, [clip], now);
    if (!kept) return [];
    useStore.setState((current) => ({ recentlyDeleted: [kept, ...current.recentlyDeleted] }));
    return [kept.id];
}
