import type { ClipVersion, SongIdea } from "../types";
import { locateIdea } from "../domain/itemLocator";
import { useStore } from "./useStore";

/**
 * One write for a clip's words (title, notes) from any editor (data-safety audit
 * 2026-11-02, root cause 4). It is keyed by the ids the editor OPENED on, reads the
 * idea where it lives at the moment of saving, and writes only the fields in the
 * patch — so an editor that only renamed never puts back the older notes it was
 * holding (12c C-H1), and a note never lands on whatever clip happens to be playing
 * when Save is pressed (12a A-H2).
 *
 * A clip idea keeps its notes twice (the idea's and its first clip's). Every write
 * here keeps the two the same, so whichever a screen reads, it reads the latest.
 */
export type ClipTextPatch = Partial<Pick<ClipVersion, "title" | "notes" | "isTitleAutoGenerated">>;

export function applyClipTextPatch(
  idea: SongIdea,
  clipId: string,
  patch: ClipTextPatch,
  ideaPatch?: Partial<Pick<SongIdea, "title">>
): SongIdea {
  const clipIndex = idea.clips.findIndex((clip) => clip.id === clipId);
  if (clipIndex < 0) return idea;
  const mirrorsIdea = idea.kind === "clip" && clipIndex === 0;
  return {
    ...idea,
    ...(ideaPatch ?? null),
    ...(mirrorsIdea && patch.notes !== undefined ? { notes: patch.notes } : null),
    clips: idea.clips.map((clip) => (clip.id === clipId ? { ...clip, ...patch } : clip)),
  };
}

/** False when nothing was written: the clip is gone, or its workspace is read-only. */
export function saveClipTextEdits(
  ideaId: string,
  clipId: string,
  patch: ClipTextPatch,
  ideaPatch?: Partial<Pick<SongIdea, "title">>
): boolean {
  if (Object.keys(patch).length === 0 && (!ideaPatch || Object.keys(ideaPatch).length === 0)) return true;
  const state = useStore.getState();
  const located = locateIdea(state.workspaces, ideaId);
  if (!located || !located.idea.clips.some((clip) => clip.id === clipId)) return false;
  return state.updateIdeas(
    (ideas) => ideas.map((idea) => (idea.id === ideaId ? applyClipTextPatch(idea, clipId, patch, ideaPatch) : idea)),
    { workspaceId: located.workspace.id }
  );
}
