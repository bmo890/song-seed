import { useMemo, useRef, useState } from "react";
import { buildLineageTitlePlan } from "../../../domain/clipLineageTitles";
import {
  showLineageRenamePrompt,
  type LineageRenamePromptInfo,
} from "../../../domain/clipLineageRenamePrompt";
import { useStore } from "../../../state/useStore";
import { locateIdea } from "../../../domain/itemLocator";
import { changedFields, editorDraftKey } from "../../../domain/editorDrafts";
import { saveClipTextEdits } from "../../../state/clipTextEdits";
import { type ClipVersion, type SongIdea } from "../../../types";

/** The idea wherever it lives: the sketch page shows ideas from any workspace,
 *  and an active-only lookup dropped typed clip notes (data-safety audit 04-H2). */
function getCurrentStoreIdea(ideaId: string | null): SongIdea | null {
  return locateIdea(useStore.getState().workspaces, ideaId)?.idea ?? null;
}

// ── hook ───────────────────────────────────────────────────────────────────

export function useSongClipEditing(selectedIdea: SongIdea | null) {
  const [editingClipId, setEditingClipId] = useState<string | null>(null);
  const [editingClipDraft, setEditingClipDraft] = useState("");
  const [editingClipNotesDraft, setEditingClipNotesDraft] = useState("");
  const [notesSheetClipId, setNotesSheetClipId] = useState<string | null>(null);
  // What the take held when its sheet or inline form opened: a save writes only what
  // moved from this, onto the take as it is now (audit 2026-11-02, root cause 4).
  const openedRef = useRef<{ clipId: string; title: string; notes: string } | null>(null);

  const currentIdeaId = selectedIdea?.id ?? null;

  const notesSheetClip = useMemo(
    () =>
      notesSheetClipId && selectedIdea
        ? selectedIdea.clips.find((clip) => clip.id === notesSheetClipId) ?? null
        : null,
    [notesSheetClipId, selectedIdea]
  );

  function openNotesSheet(clip: ClipVersion) {
    openedRef.current = { clipId: clip.id, title: clip.title, notes: clip.notes || "" };
    setEditingClipDraft(clip.title);
    setEditingClipNotesDraft(clip.notes || "");
    setNotesSheetClipId(clip.id);
  }

  /**
   * Commits the title/notes change to the store and returns rename-prompt info
   * if other clips in the lineage need updating. Returns null when no prompt
   * is needed.
   */
  function commitClipTitleSave(targetClipId: string): LineageRenamePromptInfo | null {
    const currentIdea = getCurrentStoreIdea(currentIdeaId);
    if (!currentIdeaId || !currentIdea) {
      return null;
    }

    const targetClip = currentIdea.clips.find((clip) => clip.id === targetClipId);
    if (!targetClip) return null;
    const opened =
      openedRef.current?.clipId === targetClipId
        ? openedRef.current
        : { title: targetClip.title, notes: targetClip.notes || "" };
    const changed = changedFields(
      { title: opened.title, notes: opened.notes.trim() },
      { title: editingClipDraft, notes: editingClipNotesDraft.trim() }
    );

    const plan =
      changed.title !== undefined ? buildLineageTitlePlan(currentIdea.clips, targetClipId, editingClipDraft) : null;
    if (changed.title !== undefined && !plan) {
      return null;
    }

    saveClipTextEdits(currentIdeaId, targetClipId, {
      ...(plan ? { title: plan.savedTitle, isTitleAutoGenerated: false } : null),
      ...(changed.notes !== undefined ? { notes: changed.notes } : null),
    });

    if (!plan) {
      return null;
    }
    const lineageSize = plan.orderedClips.length;

    if (!plan.lineage || lineageSize <= 1 || plan.targetIndex < 0) {
      return null;
    }

    const renames = plan.renames;
    if (renames.length === 0) {
      return null;
    }

    return { ideaId: currentIdeaId, renames };
  }

  function saveNotesSheet() {
    if (!notesSheetClipId) return;
    const clipId = notesSheetClipId;
    const promptInfo = commitClipTitleSave(clipId);
    // Close the sheet first so the Alert doesn't fight a dismissing BottomSheet.
    setNotesSheetClipId(null);
    if (promptInfo) {
      setTimeout(() => {
        showLineageRenamePrompt(promptInfo);
      }, 400);
    }
  }

  function beginEditingClip(clip: ClipVersion) {
    openedRef.current = { clipId: clip.id, title: clip.title, notes: clip.notes || "" };
    setEditingClipId(clip.id);
    setEditingClipDraft(clip.title);
    setEditingClipNotesDraft(clip.notes || "");
  }

  function saveEditingClip(clipId: string) {
    const promptInfo = commitClipTitleSave(clipId);
    setEditingClipId(null);
    if (promptInfo) {
      // Small delay so the inline edit UI collapses before the Alert appears.
      setTimeout(() => {
        showLineageRenamePrompt(promptInfo);
      }, 100);
    }
  }

  function cancelEditing() {
    setEditingClipId(null);
  }

  function closeNotesSheet() {
    setNotesSheetClipId(null);
  }

  return {
    /** The open notes sheet's key in the unsaved-words store. */
    notesSheetDraftKey:
      currentIdeaId && notesSheetClipId ? editorDraftKey("clipText", currentIdeaId, notesSheetClipId) : null,
    editingClipId,
    editingClipDraft,
    setEditingClipDraft,
    editingClipNotesDraft,
    setEditingClipNotesDraft,
    notesSheetClip,
    openNotesSheet,
    saveNotesSheet,
    beginEditingClip,
    saveEditingClip,
    cancelEditing,
    closeNotesSheet,
  };
}
