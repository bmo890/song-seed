const DAY = 24 * 60 * 60 * 1000;

type Audio = { audioUri: string; durationMs?: number; waveformPeaks?: number[] };

function chord(id: string, name: string, at: number): ChordPlacement {
  const root = name[0] as ChordPlacement["root"];
  const quality = name.endsWith("m") ? "m" : undefined;
  return { id, chord: name, at, root, accidental: "natural", ...(quality ? { quality } : {}) };
}

function line(id: string, text: string, chords: Array<[string, number]> = []): LyricsLine {
  return { id, text, chords: chords.map(([name, at], i) => chord(`${id}-c${i}`, name, at)) };
}

function collection(id: string, workspaceId: string, title: string, createdAt: number, updatedAt = createdAt): Collection {
  return {
    id,
    title,
    workspaceId,
    parentCollectionId: null,
    createdAt,
    updatedAt,
    ideasListState: { hiddenIdeaIds: [], hiddenDays: [] },
  };
}

function take(
  id: string,
  title: string,
  audio: Audio | undefined,
  createdAt: number,
  extra: Partial<ClipVersion> = {}
): ClipVersion {
  return {
    id,
    title,
    notes: "",
    createdAt,
    isPrimary: false,
    isTitleAutoGenerated: false,
    ...(audio ?? {}),
    ...extra,
  };
}

function clipIdea(
  id: string,
  collectionId: string,
  title: string,
  audio: Audio | undefined,
  createdAt: number,
  notes = ""
): SongIdea {
  return {
    id,
    title,
    notes,
    status: "clip",
    completionPct: 0,
    kind: "clip",
    collectionId,
    clips: [take(`${id}-clip`, title, audio, createdAt, { isPrimary: true })],
    isTitleAutoGenerated: false,
    createdAt,
    lastActivityAt: createdAt,
  };
}

function sketch(
  id: string,
  collectionId: string,
  title: string,
  status: SongIdea["status"],
  takes: ClipVersion[],
  createdAt: number,
  lastActivityAt: number,
  lyrics?: string[]
): SongIdea {
  return {
    id,
    title,
    notes: "",
    status,
    completionPct: status === "song" ? 100 : status === "stem" ? 70 : status === "sprout" ? 40 : 15,
    kind: "project",
    collectionId,
    isTitleAutoGenerated: false,
    createdAt,
    lastActivityAt,
    clips: takes.map((clip, i) => ({ ...clip, isPrimary: i === takes.length - 1 })),
    ...(lyrics
      ? {
          lyrics: {
            versions: [
              {
                id: `${id}-lyr`,
                createdAt: lastActivityAt,
                updatedAt: lastActivityAt,
                document: { lines: lyrics.map((text, i) => line(`${id}-l${i}`, text)) },
              },
            ],
          },
        }
      : {}),
  };
}

/** Harbor Lights as Sam sent it: the same takes, marks, layer, lyrics and chart,
 *  plus his note on the take, waiting in Received. */
function stageReceivedParcel(harbor: SongIdea) {
  const pkg = "ws-store-parcel";
  const now = Date.now();
  const col = "col-store-parcel";
  const copy: SongIdea = {
    ...harbor,
    id: "idea-store-parcel-harbor",
    collectionId: col,
    clips: harbor.clips.map((clip) => ({
      ...clip,
      id: `${clip.id}-p`,
      parentClipId: clip.parentClipId ? `${clip.parentClipId}-p` : undefined,
      notes: clip.isPrimary ? "Learn the bridge before Friday. The harmony comes in on the chorus." : clip.notes,
    })),
  };
  const parcel: Workspace = {
    id: pkg,
    title: "Harbor Lights",
    origin: "received",
    received: {
      senderName: "Sam",
      senderUserId: null,
      transferId: `dev-store-${now}`,
      receivedAt: now - 20 * 60 * 1000,
      shareKind: "sketch",
      shareTitle: "Harbor Lights",
      message: "New chorus. Learn the bridge before Friday.",
    },
    collections: [collection(col, pkg, "Harbor Lights", now)],
    ideas: [copy],
  };
  // Restaging replaces the staged parcel (it shares the library's audio, owns none).
  useStore.setState((state) => ({ workspaces: [...state.workspaces.filter((w) => w.id !== pkg), parcel] }));
}

