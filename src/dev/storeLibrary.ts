// Imports the audio in Documents/dev-samples/ (sample-01 … sample-12, pushed by
// hand) through the real pipeline, then lays out "My Songs" around them: the
// Harbor Lights sketch (stacked versions, sections, a pin, a harmony layer,
// chorded lyrics), loose clips, a shelf, a setlist, a playlist and a songbook.
// Empty workspaces (the fresh-install default) are replaced; nothing with ideas is.
