type OnRecorded = (
  payload: {
    audioUri: string;
    durationMs?: number;
    waveformPeaks?: number[];
    /** ms cut from the front of the take at save (count-in/pre-roll head). 0 = untrimmed. */
    headTrimmedMs?: number;
    /**
     * 1ms high-passed onset envelope of the take, already shifted into FILE ms (the trimmed
     * head is dropped). This is the signal the beat grid is verified against — see
     * `domain/onsetEnvelope.ts` for why the waveform sidecar cannot serve.
     */
    onsetEnvelope?: OnsetEnvelope | null;
  }
) => void | boolean | Promise<void | boolean>;

// Dev used to throttle the stream to 120ms because each delivery cost a React re-render
// plus an UNBOUNDED Skia path rebuild, and dev-mode JS couldn't keep up. Both costs are
// gone (the rebuild is bounded to the visible tape; the scroll is UI-thread) — and the
// throttle itself had become the visible problem: at 8 deliveries/second the live tape's
// wave trails the playhead by a whole chunk, which reads as "built left of the playhead".
// Dev now streams at the production cadence, so what the founder tests is what ships.
/** Capture format. The onset envelope's bin duration is derived from this, so a mismatch
 *  between what the recorder is configured with and what the envelope assumes would put a
 *  proportional error into every beat grid — named once, used everywhere. */
const CAPTURE_SAMPLE_RATE = RECORDING_TAKE_SHAPE.sampleRate;
const CAPTURE_CHANNELS = RECORDING_TAKE_SHAPE.channels;
const LIVE_WAVEFORM_SEGMENT_MS = RECORDING_TAKE_SHAPE.segmentDurationMs;
const LIVE_STREAM_INTERVAL_MS = 40;
const ANALYSIS_SEGMENT_MS = 75;
/** Below this the head trim is noise, not a count-in — skip the re-render. */
const MIN_HEAD_TRIM_MS = 24;
/** Ignore absurd trim values (a count-in head is at most a few bars). */
const MAX_HEAD_TRIM_MS = 30_000;

/** Locate the clip the attach step just created, by the managed file it references. */
function findClipByAudioUri(audioUri: string) {
  for (const workspace of useStore.getState().workspaces) {
    for (const idea of workspace.ideas) {
      const clip = idea.clips.find((candidate) => candidate.audioUri === audioUri);
      if (clip) {
        return {
          ideaId: idea.id,
          ideaTitle: idea.title,
          ideaTitleAutoGenerated: idea.isTitleAutoGenerated !== false,
          clip,
        };
      }
    }
  }
  return null;
}

function getErrorMessage(error: unknown) {
  return error instanceof Error ? error.message : String(error);
}

function isNotificationPermissionError(error: unknown) {
  const message = getErrorMessage(error).toLowerCase();
  return message.includes("notification permission") || message.includes("post_notifications");
}

// There is ONE pending-take marker. After a save that ended in "kept for recovery" the
// take lives only as the recorder's temp file plus that marker — and starting another
// take would overwrite the marker, orphaning the first one for good. Recover it into
// the library before a new take can claim the slot.
let unrecoveredTakeThisSession = false;

async function recoverKeptTakeBeforeNewOne() {
  if (!unrecoveredTakeThisSession) return;
  unrecoveredTakeThisSession = false;
  try {
    const result = await recoverPendingRecordingSession({ lightweight: true });
    if (result.status === "failed") persistLog("recording.flushFailed", `in-session recovery: ${result.message}`);
  } catch (error) {
    persistLog("recording.flushFailed", `in-session recovery: ${describeError(error)}`);
  }
}

// One owner for the recording role app-wide: the take outlives the screen that
// started it, and the instance that saves it must release the SAME claim.
const RECORDING_AUDIO_SESSION_OWNER = createAudioSessionOwner("recording");

// The input last applied to the session ("default" or a device id). Re-selecting
// the same input cost 110–240 ms on every take (2026-10-17 latency pass), so it is
// skipped while the recording session stays claimed and nothing changed. Any
// device event or session release forgets it, and the next take re-applies.
let appliedInputKey: string | null = null;
// The selection in flight, so an early warm-up and a record tap never both pay for it.
let inputApplying: { key: string; promise: Promise<string> } | null = null;
let deviceWatchInstalled = false;
function watchDevicesOnce() {
  if (deviceWatchInstalled) return;
  deviceWatchInstalled = true;
  try {
    audioDeviceManager.addDeviceChangeListener(() => {
      appliedInputKey = null;
    });
  } catch {
    // No device events: always re-apply (the old behaviour).
    deviceWatchInstalled = false;
  }
}

// Discard's housekeeping (delete the file, clear the recovery marker, release the
// session) runs after the screen has already moved on. The next take waits for it
// before writing its own recovery marker, so a late clear can never wipe it.
// A preparation waits only for the housekeeping queued BEFORE it began (captured
// synchronously): a prewarm release queued later waits on that preparation, and
// waiting on it back would deadlock the recorder.
let discardCleanup: Promise<void> = Promise.resolve();

export function useRecording(onRecorded: OnRecorded, preferredInputId: string | null) {
  const { t } = useTranslation();
  const recorder = useSharedAudioRecorder();
  // Every per-take fact (live tape, onset envelope, head trim, capture start, flags)
  // lives in the app-wide take session, not in this instance: the recorder screen can
  // be minimized and reopened mid-take, and the dock reads the same take.
  const take = getRecordingTakeSession(RECORDING_TAKE_SHAPE);
  const headTrim = useTakeHeadTrim(take);
  // The live tape is NOT subscribed here: it re-renders ~25×/s during a take, and
  // subscribing the whole recorder to it re-rendered the entire screen at that rate.
  // The tape leaf subscribes to the session itself (LiveTakeTape).
  const { token: interruptionToken, reason: lastInterruptionReason } = useTakeInterruption(take);
  const permissionRequestRef = useRef<Promise<boolean> | null>(null);
  const prepareInFlightRef = useRef<Promise<boolean> | null>(null);
  // The prepared recorder came from a prewarm, not this tap: if it went stale
  // while waiting (a route or media-services change), the tap retries from scratch.
  const prewarmedRef = useRef(false);
  // A save still reads the take (file, trims, envelope) after the recorder stops;
  // a prewarm must not begin the next take under it.
  const saveInFlightRef = useRef(false);
  const startInFlightRef = useRef(false);
  const recordingIdeaId = useStore((s) => s.recordingIdeaId);
  const setPreferredRecordingInputId = useStore((s) => s.setPreferredRecordingInputId);
  const elapsedLiveRef = useRef(0);
  const displayElapsedMs = useRecordingDisplayElapsed(
    {
      durationMs: recorder.durationMs,
      isRecording: recorder.isRecording,
      isPaused: recorder.isPaused,
    },
    { liveRef: elapsedLiveRef }
  );
  const headTrimRef = useRef(headTrim);
  headTrimRef.current = headTrim;
  /** The exact elapsed time right now (no render), with the head trim applied
   *  like `elapsedMs`. For the moments that need precision between the
   *  once-a-second readout commits. */
  const readElapsedMs = useCallback(() => {
    const trim = headTrimRef.current;
    return trim.pending ? 0 : Math.max(0, elapsedLiveRef.current - trim.ms);
  }, []);

  useEffect(() => {
    if (!recorder.isRecording || recorder.isPaused) {
      return;
    }
    take.observeDuration(recorder.durationMs);
  }, [recorder.durationMs, recorder.isPaused, recorder.isRecording, take]);

  const resetOnsetEnvelope = take.resetOnsetEnvelope;
  const resetLiveWaveform = take.resetLiveWaveform;
  const resetCaptureStartEstimate = take.resetCaptureStart;

  /** When capture began (epoch ms): the native recorder's measured sample-0 time when
   *  the patched binary reports one, else the duration-based estimate, else the JS-side
   *  stamp taken just before the native start call. Null when nothing is recording. */
  const getCaptureStartEpochMs = take.getCaptureStartEpochMs;

  /** Mark the in-flight take as record-through: elapsed reads 0 until the head is known. */
  function armHeadTrim() {
    take.headTrim.set({ pending: true, ms: 0 });
  }

  /** Fix the head length (ms of pre-roll to cut at save). Ends the pending state, so the
   *  live tape starts drawing at the musical start.
   *
   *  It deliberately does NOT reset the live waveform. The tape's time axis is capture ms
   *  (ms since sample 0) and the beat grid is stamped in the same axis; re-zeroing the
   *  clock here put the two on different origins, which is why the live ruler bore no
   *  relation to the beats. The count-in audio is hidden by not retaining its points, not
   *  by rewinding the clock. */
  function commitHeadTrim(ms: number) {
    const safeMs = Number.isFinite(ms) && ms > 0 && ms <= MAX_HEAD_TRIM_MS ? Math.round(ms) : 0;
    take.headTrim.set({ pending: false, ms: safeMs });
  }

  /** Drop any head-trim bookkeeping (interruption/cancel paths). */
  function abortHeadTrim() {
    take.headTrim.set({ pending: false, ms: 0 });
  }
  // Single-line card by design: "● Recording… • 0:42". One fixed title.
  const recordingNotificationTitle = "Recording…";
  async function claimRecordingAudioSession() {
    await activateRecordingAudioSession({ ownerId: RECORDING_AUDIO_SESSION_OWNER });
  }

  async function releaseRecordingAudioSession() {
    // iOS: a released session can lose its preferred input, so the next take
    // re-applies. Android's input rides the recorder config, not the session, and
    // re-selecting the default mic cost ~500 ms per take on the founder's phone
    // (diagnostic trace 2026-10-17); only a device event re-applies there.
    if (Platform.OS !== "android") appliedInputKey = null;
    await releaseAudioSessionOwner(RECORDING_AUDIO_SESSION_OWNER);
  }

  async function applyPreferredInput() {
    watchDevicesOnce();
    const key = preferredInputId ?? "default";
    if (appliedInputKey === key) return;
    let applying = inputApplying?.key === key ? inputApplying : null;
    if (!applying) {
      const started = { key, promise: applyPreferredInputNow() };
      inputApplying = applying = started;
      void started.promise
        .finally(() => {
          if (inputApplying === started) inputApplying = null;
        })
        .catch(() => {});
    }
    appliedInputKey = await applying.promise;
  }

  /** Whether a Bluetooth device is listed (a record-ready route would move it
   *  to its call profile before the writer chose to record). */
  async function bluetoothInReach() {
    const known = audioDeviceManager.getRawDevices();
    const devices = known.length > 0 ? known : await audioDeviceManager.getAvailableDevices();
    return devices.some((device) => device.type === "bluetooth");
  }

  /**
   * Android's half of the warm-up (2026-10-17): select the input while the
   * recorder opens instead of inside the first record tap (~500 ms on the
   * founder's phone). Only the input: the audio mode is left alone, so music
   * from other apps is untouched. Not with Bluetooth in reach (selecting there
   * can start the headset's call profile), and never under a take. The native
   * recorder is not prepared ahead here; Android's cannot be un-prepared.
   */
  async function warmInput() {
    if (recorder.isRecording || recorder.isPaused || take.facts.recordingStartedAt !== null) return;
    if ((preferredInputId ?? "default") === appliedInputKey) return;
    beginRecordTrace("warm");
    try {
      if (await bluetoothInReach()) {
        endRecordTrace("warm", "skip:bt");
        return;
      }
      await timedStep("record.prewarm.input", applyPreferredInput());
      endRecordTrace("warm", "input");
    } catch {
      endRecordTrace("warm", "skip:fail");
    }
  }

  /** Applies the writer's input; returns the key it actually landed on. */
  async function applyPreferredInputNow(): Promise<string> {
    if (preferredInputId) {
      try {
        const selectionResult = await audioDeviceManager.selectDevice(preferredInputId);
        if (selectionResult !== false) {
          return preferredInputId;
        }
      } catch (selectionError) {
        console.warn("Preferred input selection failed", selectionError);
      }

      try {
        await audioDeviceManager.resetToDefaultDevice();
      } catch (resetError) {
        console.warn("Recording input reset after stale preference failed", resetError);
      }
      setPreferredRecordingInputId(null);
      return "default";
    }

    try {
      await audioDeviceManager.resetToDefaultDevice();
    } catch (resetError) {
      console.warn("Recording input reset failed", resetError);
    }
    return "default";
  }

  async function requestMicrophonePermission() {
    const permission = await ExpoAudioStreamModule.requestPermissionsAsync();
    const granted = permission?.granted ?? permission?.status === "granted";

    if (granted) {
      return true;
    }

    if (permission?.canAskAgain === false) {
      AppAlert.custom(
        t("recordingErrors.micTitle"),
        t("recordingErrors.micBlocked"),
        [
          { label: t("recordingErrors.cancel"), style: "cancel" },
          {
            label: t("recordingErrors.openSettings"),
            style: "default",
            icon: "settings-outline",
            onPress: () => {
              void Linking.openSettings();
            },
          },
        ]
      );
    } else {
      AppAlert.info(t("recordingErrors.micTitle"), t("recordingErrors.micNeeded"));
    }

    return false;
  }

  function showNotificationPermissionAlert(blocked: boolean) {
    const message = blocked
      ? t("recordingErrors.notificationBlocked")
      : t("recordingErrors.notificationNeeded");

    if (!blocked) {
      AppAlert.info(t("recordingErrors.notificationTitle"), message);
      return;
    }

    AppAlert.custom(t("recordingErrors.notificationTitle"), message, [
      { label: t("recordingErrors.cancel"), style: "cancel" },
      {
        label: t("recordingErrors.openSettings"),
        style: "default",
        icon: "settings-outline",
        onPress: () => {
          void Linking.openSettings();
        },
      },
    ]);
  }

  async function requestRecordingNotificationPermission() {
    if (Platform.OS !== "android") {
      return true;
    }

    const currentPermission = await ExpoAudioStreamModule.getNotificationPermissionsAsync();
    const alreadyGranted =
      currentPermission?.granted ?? currentPermission?.status === "granted";
    if (alreadyGranted) {
      return true;
    }

    const permission = await ExpoAudioStreamModule.requestNotificationPermissionsAsync();
    const granted = permission?.granted ?? permission?.status === "granted";
    if (granted) {
      return true;
    }

    showNotificationPermissionAlert(permission?.canAskAgain === false);
    return false;
  }

  async function requestRecordingPermissions() {
    if (permissionRequestRef.current) {
      return permissionRequestRef.current;
    }

    const request = (async () => {
      if (!(await requestMicrophonePermission())) {
        return false;
      }
      return requestRecordingNotificationPermission();
    })();
    permissionRequestRef.current = request;

    try {
      return await request;
    } finally {
      if (permissionRequestRef.current === request) {
        permissionRequestRef.current = null;
      }
    }
  }

  function showRecordingFailure(error: unknown, fallback: string) {
    if (isNotificationPermissionError(error)) {
      showNotificationPermissionAlert(true);
      return;
    }
    AppAlert.error(t("recordingErrors.failed"), fallback);
  }

  async function rollbackFailedRecordingStart(
    nativeStartAttempted: boolean,
    audioSessionClaimed: boolean
  ) {
    take.facts.prepared = false;
    take.facts.recordingStartedAt = null;
    take.facts.sessionPersisted = false;

    if (nativeStartAttempted || recorder.isRecording || recorder.isPaused) {
      try {
        take.facts.expectedStop = true;
        await recorder.stopRecording();
      } catch (stopError) {
        take.facts.expectedStop = false;
        console.warn("Recording rollback stop failed", stopError);
      }
    }

    if (nativeStartAttempted) {
      await clearPendingRecordingSession().catch((error) => {
        console.warn("Recording rollback recovery cleanup failed", error);
      });
    }
    if (audioSessionClaimed) {
      await releaseRecordingAudioSession().catch((error) => {
        console.warn("Recording audio session release after start failure failed", error);
      });
    }
  }

  function buildRecordingConfig(): RecordingConfig {
    return {
      // Session-level selection (applyPreferredInput) covers iOS; Android's recorder only
      // honors the choice when the id rides the config into the native AudioRecord
      // (patched: AudioRecord.setPreferredDevice).
      deviceId: preferredInputId ?? undefined,
      sampleRate: CAPTURE_SAMPLE_RATE as SampleRate,
      channels: CAPTURE_CHANNELS as 1,
      interval: LIVE_STREAM_INTERVAL_MS,
      intervalAnalysis: 75,
      segmentDurationMs: 75,
      streamFormat: "float32" as const,
      enableProcessing: true,
      features: { energy: true, rms: true },
      autoResumeAfterInterruption: true,
      bufferDurationSeconds: 0.15,
      keepAwake: true,
      showNotification: true,
      // Deliberately no waveform: the recording card stays a quiet two-line
      // notification (context title + destination) with the record-red accent.
      showWaveformInNotification: false,
      notification: {
        title: recordingNotificationTitle,
        android: {
          // v2: channel importance changed LOW -> DEFAULT for Android 16 Live
          // Updates eligibility; channels are immutable once created, so the id
          // must change for existing installs to pick it up.
          channelId: "songnook-recording-v2",
          channelName: t("recordingErrors.notificationChannel"),
          channelDescription: t("recordingErrors.notificationChannelHint"),
          notificationId: 4101,
          priority: "high" as const,
          accentColor: colors.record,
          showPauseResumeActions: true,
        },
        ios: {
          categoryIdentifier: "songnook-recording",
        },
      },
      android: {
        audioFocusStrategy: "background" as const,
      },
      ios: {
        audioSession: {
          category: "PlayAndRecord" as const,
          mode: "Measurement" as const,
          categoryOptions: ["MixWithOthers", "AllowBluetooth", "AllowBluetoothA2DP", "DefaultToSpeaker"] as const,
        },
      },
      onAudioStream: async (event: any) => {
        // Record-through: while the head is still pending (count-in / pre-roll), capture is
        // rolling but this audio will be trimmed off at save. Don't DRAW it on the live
        // tape — otherwise the tape shows a silent count-in lead that the saved (trimmed)
        // file doesn't have. The clock keeps running through it, so the tape and the beat
        // grid stay in one axis (capture ms); dropping these deliveries entirely is what
        // used to break that.
        take.appendAudioStream(event, { retainPoints: !take.headTrim.get().pending });
        // The click bleed's onset envelope, accumulated from the same buffers. This is the
        // signal the beat grid is verified against at save; measured against the waveform
        // sidecar the app used to comb, a click under real playing does not exist at all
        // (docs/qa/grid-truth.md). Built here because it costs one subtract per sample and
        // the samples are already in hand — nothing to decode, nothing to be preempted.
        if (event.streamFormat === "float32" && event.data instanceof Float32Array) {
          take.appendOnset(event.data);
        }
        const nativeCaptureStart = (event as { captureStartTimeEpochMs?: unknown })
          .captureStartTimeEpochMs;
        if (
          take.facts.captureStartNative === null &&
          typeof nativeCaptureStart === "number" &&
          Number.isFinite(nativeCaptureStart) &&
          nativeCaptureStart > 0
        ) {
          const source =
            typeof (event as { captureStartSource?: unknown }).captureStartSource === "string"
              ? ((event as { captureStartSource?: string }).captureStartSource as string)
              : "native";
          take.facts.captureStartNative = { epochMs: nativeCaptureStart, source };
          const estimated = take.facts.captureStartEstimate.epochMs;
          console.log(
            `[timing] captureStart native=${Math.round(nativeCaptureStart)} (${source})` +
              (estimated !== null
                ? ` estimatorDelta=${Math.round(estimated - nativeCaptureStart)}ms`
                : "")
          );
        }
        if (!event.fileUri || take.facts.sessionPersisted) return;
        take.facts.sessionPersisted = true;
        const recordingStartedAt = take.facts.recordingStartedAt ?? Date.now();
        void persistPendingRecordingSession(event.fileUri, recordingStartedAt);
      },
      onRecordingInterrupted: (event) => {
        const isExpectedStoppedEvent =
          event.reason === "recordingStopped" && take.facts.expectedStop;
        take.facts.expectedStop = false;
        if (isExpectedStoppedEvent) {
          return;
        }
        take.facts.prepared = false;
        // A committed head stays valid (the front of the file is unchanged); only a
        // mid-count-in interruption leaves an unmeasurable pending head to drop.
        if (take.headTrim.get().pending) take.headTrim.set({ pending: false, ms: 0 });
        take.noteInterruption(event.reason);
        appliedInputKey = null;
        void releaseAudioSessionOwner(RECORDING_AUDIO_SESSION_OWNER).catch((error) => {
          console.warn("Recording audio session release after interruption failed", error);
        });
      },
      onAudioAnalysis: async () => {},
    };
  }

  /** Get the recorder ready to start (input, session, native prepare). Callers
   *  share one in-flight preparation: a record tap that lands while the screen's
   *  prewarm is still preparing waits for it instead of failing. */
  function prepareRecording(): Promise<boolean> {
    if (recorder.isRecording || recorder.isPaused) return Promise.resolve(false);
    if (take.facts.prepared) return Promise.resolve(true);
    if (prepareInFlightRef.current) return prepareInFlightRef.current;
    const run = prepareRecordingNow(discardCleanup).finally(() => {
      prepareInFlightRef.current = null;
    });
    prepareInFlightRef.current = run;
    return run;
  }

  async function prepareRecordingNow(housekeeping: Promise<void>) {
    try {
      await housekeeping;
      const hasPermission = await requestRecordingPermissions();
      if (!hasPermission) {
        return false;
      }

      await timedStep("record.input", applyPreferredInput());

      await timedStep("record.session", claimRecordingAudioSession());
      take.beginTake();
      await timedStep("record.prepare", recorder.prepareRecording(buildRecordingConfig()));
      take.facts.prepared = true;
      return true;
    } catch (err) {
      await releaseRecordingAudioSession().catch((error) => {
        console.warn("Recording audio session release after prepare failure failed", error);
      });
      console.warn("Recording prepare failed", err);
      showRecordingFailure(err, t("recordingErrors.prepareFailed"));
      return false;
    }
  }

  /**
   * Prepare ahead of the record tap (2026-10-17 latency pass). An unprepared
   * start makes the native recorder reset the audio session (deactivate, a fixed
   * 100 ms sleep, reactivate) and build its engine inside the tap: ~350 ms on the
   * simulator, more with Bluetooth. Preparing does not open the microphone (the
   * engine is not started), and runs only when permission was already granted,
   * so opening the recorder never prompts. Failures are silent: the tap falls
   * back to preparing itself, exactly as before.
   *
   * Not with Bluetooth in reach: a record-ready session moves a headset to its
   * call profile, and the writer's music would drop to call quality before they
   * have chosen to record. Those takes prepare on the tap, as before.
   */
  function prewarmRecording(): Promise<boolean> {
    // A take that exists (even paused, or mid-flicker of the recorder's state)
    // owns the recorder; React state alone can lag it.
    const takeLive = () =>
      recorder.isRecording ||
      recorder.isPaused ||
      startInFlightRef.current ||
      saveInFlightRef.current ||
      take.facts.recordingStartedAt !== null;
    if (takeLive()) return Promise.resolve(false);
    if (take.facts.prepared) return Promise.resolve(true);
    if (prepareInFlightRef.current) return prepareInFlightRef.current;
    // Claimed before the first await, so a tap that lands mid-check waits for this.
    const housekeeping = discardCleanup;
    beginRecordTrace("warm");
    const run = (async () => {
      try {
        const mic = await ExpoAudioStreamModule.getPermissionsAsync();
        if (!(mic?.granted ?? mic?.status === "granted")) return skipWarm("perm");
        if (Platform.OS === "android") {
          const notif = await ExpoAudioStreamModule.getNotificationPermissionsAsync();
          if (!(notif?.granted ?? notif?.status === "granted")) return skipWarm("perm");
        }
        if (await bluetoothInReach()) return skipWarm("bt");
      } catch {
        return skipWarm("check");
      }
      try {
        await housekeeping;
        if (take.facts.recordingStartedAt !== null || saveInFlightRef.current) return skipWarm("busy");
        await timedStep("record.prewarm.input", applyPreferredInput());
        await timedStep("record.prewarm.session", claimRecordingAudioSession());
        take.beginTake();
        await timedStep("record.prewarm.native", recorder.prepareRecording(buildRecordingConfig()));
        take.facts.prepared = true;
        prewarmedRef.current = true;
        endRecordTrace("warm", "ok");
        return true;
      } catch (error) {
        console.warn("Recording prewarm failed", error);
        await releaseRecordingAudioSession().catch(() => {});
        return skipWarm("fail");
      }
    })().finally(() => {
      prepareInFlightRef.current = null;
    });
    prepareInFlightRef.current = run;
    return run;
  }

  function skipWarm(reason: string) {
    endRecordTrace("warm", `skip:${reason}`);
    return false;
  }

  /** For the record trace: whether the tap finds a ready recorder. */
  function prewarmState(): "ready" | "warming" | "cold" {
    if (take.facts.prepared) return "ready";
    return prepareInFlightRef.current ? "warming" : "cold";
  }

  /** Undo a prewarm the writer never used (leaving the recorder). Nothing was
   *  captured, so the recovery marker is left alone: it may still hold a kept
   *  take from before. Queued with discard's housekeeping, so the next prepare
   *  waits for it. */
  function releasePrewarm() {
    const inFlight = prepareInFlightRef.current;
    discardCleanup = discardCleanup.then(async () => {
      if (inFlight) await inFlight.catch(() => false);
      if (!take.facts.prepared || startInFlightRef.current) return;
      take.facts.prepared = false;
      prewarmedRef.current = false;
      try {
        take.facts.expectedStop = true;
        await recorder.stopRecording();
      } catch {
        take.facts.expectedStop = false;
      }
      await releaseRecordingAudioSession().catch(() => {});
    });
    return discardCleanup;
  }


  async function startRecording() {
    if (recorder.isRecording || recorder.isPaused || startInFlightRef.current) return false;
    // A restore restarts the app the moment it lands, so a take begun under it would
    // be cut off mid-phrase (overnight check 2026-10-19). Haptics vocabulary `error`:
    // "Something failed" — the take can't start.
    const process = useProcessStore.getState().process;
    if ((process?.kind === "restore" && process.status === "running") || getRestoreRestartState()) {
      haptic.error();
      AppAlert.info(t("recording.restoreRunningTitle"), t("recording.restoreRunningBody"));
      return false;
    }
    // Prepared ahead (prewarm) or mid-prepare: start the ready recorder.
    if (take.facts.prepared || prepareInFlightRef.current) return startPreparedRecording();
    startInFlightRef.current = true;
    let nativeStartAttempted = false;
    let audioSessionClaimed = false;
    try {
      // The checks run side by side, not one after another. A discard's
      // housekeeping must land before this take writes its recovery marker.
      const [hasPermission, roomLeft] = await Promise.all([
        timedStep("perm", requestRecordingPermissions()),
        hasRoomForATake(),
        recoverKeptTakeBeforeNewOne(),
        discardCleanup,
      ]);
      if (!hasPermission) {
        return false;
      }
      if (!roomLeft) {
        // Haptics vocabulary `error`: "Something failed" — the take can't start.
        haptic.error();
        AppAlert.info(t("recording.noSpaceTitle"), t("recording.noSpaceBody"));
        return false;
      }

      try {
        if (recorder.isRecording || recorder.isPaused) {
          take.facts.expectedStop = true;
          await recorder.stopRecording();
          await new Promise(r => setTimeout(r, 150));
        }
      } catch {}

      await timedStep("record.input", applyPreferredInput());

      await timedStep("record.session", claimRecordingAudioSession());
      audioSessionClaimed = true;
      take.facts.prepared = false;
      take.beginTake();

      const recordingStartedAt = Date.now();
      take.facts.recordingStartedAt = recordingStartedAt;
      nativeStartAttempted = true;
      const startResult = await timedStep("record.start", recorder.startRecording(buildRecordingConfig()));
      if (startResult?.fileUri) {
        take.facts.sessionPersisted = true;
        await persistPendingRecordingSession(startResult.fileUri, recordingStartedAt);
      }
      return true;
    } catch (err) {
      await rollbackFailedRecordingStart(nativeStartAttempted, audioSessionClaimed);
      console.warn("Recording start failed", err);
      showRecordingFailure(err, t("recordingErrors.startFailed"));
      return false;
    } finally {
      startInFlightRef.current = false;
    }
  }

  /** A full disk mid-take is the worst place to find out (2026-08-26 audit F5).
   *  The probe fails OPEN: an error never blocks a take. */
  async function hasRoomForATake() {
    try {
      const MIN_RECORDING_FREE_BYTES = 64 * 1024 * 1024;
      const freeBytes = await timedStep("record.diskCheck", FileSystem.getFreeDiskStorageAsync());
      return !(Number.isFinite(freeBytes) && freeBytes >= 0 && freeBytes < MIN_RECORDING_FREE_BYTES);
    } catch {
      return true;
    }
  }

  async function startPreparedRecording(): Promise<boolean> {
    if (recorder.isRecording || recorder.isPaused || startInFlightRef.current) return false;
    startInFlightRef.current = true;
    let fromPrewarm = false;
    let nativeStartAttempted = false;
    let audioSessionClaimed = take.facts.prepared;
    try {
      // The checks run side by side, not one after another.
      const [permitted, roomLeft] = await Promise.all([
        timedStep("perm", requestRecordingPermissions()),
        hasRoomForATake(),
        recoverKeptTakeBeforeNewOne(),
        discardCleanup,
        prepareInFlightRef.current ?? Promise.resolve(true),
      ]);
      // A prewarm that finished meanwhile claimed the session for this take.
      audioSessionClaimed = take.facts.prepared;
      if (!permitted) {
        return false;
      }
      if (!roomLeft) {
        // Haptics vocabulary `error`: "Something failed" — the take can't start.
        haptic.error();
        AppAlert.info(t("recording.noSpaceTitle"), t("recording.noSpaceBody"));
        return false;
      }
      if (!take.facts.prepared) {
        const prepared = await prepareRecording();
        if (!prepared) {
          return false;
        }
        audioSessionClaimed = true;
      }
      fromPrewarm = prewarmedRef.current;
      prewarmedRef.current = false;

      const recordingStartedAt = Date.now();
      take.facts.recordingStartedAt = recordingStartedAt;
      resetCaptureStartEstimate();
      take.headTrim.set({ pending: false, ms: 0 });
      nativeStartAttempted = true;
      const startResult = await timedStep("record.start", recorder.startRecording(buildRecordingConfig()));
      take.facts.prepared = false;
      if (startResult?.fileUri) {
        take.facts.sessionPersisted = true;
        await persistPendingRecordingSession(startResult.fileUri, recordingStartedAt);
      }
      return true;
    } catch (err) {
      await rollbackFailedRecordingStart(nativeStartAttempted, audioSessionClaimed);
      if (fromPrewarm) {
        // A recorder prepared ahead went stale; prepare afresh, as an unwarmed tap would.
        console.warn("Prewarmed recording start failed; retrying cold", err);
        startInFlightRef.current = false;
        return startRecording();
      }
      console.warn("Prepared recording start failed", err);
      showRecordingFailure(err, t("recordingErrors.startFailed"));
      return false;
    } finally {
      startInFlightRef.current = false;
    }
  }

  async function cancelPreparedRecording() {
    take.facts.prepared = false;
    prewarmedRef.current = false;
    take.facts.recordingStartedAt = null;
    take.facts.sessionPersisted = false;
    abortHeadTrim();
    resetLiveWaveform();
      resetOnsetEnvelope();
    try {
      take.facts.expectedStop = true;
      await recorder.stopRecording();
    } catch {
      take.facts.expectedStop = false;
      // Ignore cleanup failures when a prepared recorder is canceled before capture begins.
    }
    await clearPendingRecordingSession();
    await releaseRecordingAudioSession().catch((error) => {
      console.warn("Recording audio session release after prepare cancel failed", error);
    });
  }

  async function pauseRecording() {
    if (!recorder.isRecording || recorder.isPaused) return;
    try {
      await recorder.pauseRecording();
    } catch {
      AppAlert.error(t("recordingErrors.pauseFailed"), t("recordingErrors.pauseFailedBody"));
    }
  }

  async function resumeRecording() {
    if (!recorder.isPaused) return;
    try {
      // Apply any input change the user made while paused.
      await applyPreferredInput();
      await claimRecordingAudioSession();
      await recorder.resumeRecording();
    } catch {
      AppAlert.error(t("recordingErrors.resumeFailed"), t("recordingErrors.resumeFailedBody"));
    }
  }

  async function saveRecording() {
    saveInFlightRef.current = true;
    try {
      return await saveRecordingNow();
    } finally {
      saveInFlightRef.current = false;
    }
  }

  async function saveRecordingNow() {
    let managedAudioUriToCleanup: string | null = null;
    let trimTempUriToCleanup: string | null = null;
    try {
      take.facts.expectedStop = true;
      const recordingData = await timedStep("stopRecording", recorder.stopRecording(), { timeoutMs: 15_000 });
      take.facts.prepared = false;
      take.facts.recordingStartedAt = null;
      // Take the onset envelope before anything resets it — the head trim it has to be
      // shifted by isn't known yet, so keep the raw capture-axis state for now.
      const capturedOnsetState = take.getOnsetEnvelope();
      resetLiveWaveform();
      resetOnsetEnvelope();
      if (!recordingData || !recordingData.fileUri) {
        AppAlert.error(t("recordingErrors.failed"), t("recordingErrors.noFile"));
        return false;
      }

      // Record-through-count-in: cut the measured pre-roll head so the file starts at the
      // musical start (downbeat / guide start). The untrimmed recorder temp file and the
      // pending-session marker stay in place until the trimmed attach succeeds, so a
      // failure at any point still recovers the full take.
      const rawDurationMs = recordingData.durationMs ?? 0;
      const currentHeadTrim = take.headTrim.get();
      const headTrimMs = currentHeadTrim.pending ? 0 : currentHeadTrim.ms;
      take.headTrim.set({ pending: false, ms: 0 });
      let sourceAudioUri = recordingData.fileUri;
      let headTrimmedMs = 0;
      if (headTrimMs >= MIN_HEAD_TRIM_MS && rawDurationMs > headTrimMs + 250) {
        try {
          const trimmed = await trimAudioRanges({
            fileUri: recordingData.fileUri,
            mode: "single",
            startTimeMs: headTrimMs,
            endTimeMs: Math.max(rawDurationMs, headTrimMs + 1),
          });
          sourceAudioUri = trimmed.uri;
          trimTempUriToCleanup = trimmed.uri;
          headTrimmedMs = headTrimMs;
          console.log(`[timing] trimmed ${headTrimMs}ms head off the saved take`);
        } catch (trimError) {
          console.warn("Recording head trim failed; keeping the untrimmed take", trimError);
        }
      } else if (headTrimMs > 0) {
        console.log(
          `[timing] head trim of ${headTrimMs}ms skipped (take too short or below threshold)`
        );
      }

      // Prefer the capture-time analysis (real RMS/peak per ~75ms segment of the
      // actual take) over a post-hoc re-decode — the re-decode path can fall back
      // to the synthetic placeholder waveform, which is what made stored waveforms
      // look unrelated to the audio. Only use managedAudio's peaks if the recorder
      // produced no analysis. The analysis covers the UNTRIMMED capture, so drop the
      // segments that fell inside the trimmed head to keep the waveform aligned.
      // Drop the analysis segments that fell inside the trimmed head, using the analysis's
      // OWN segment duration (not the assumed constant) so the kept peaks line up exactly
      // with the trimmed audio the clip references.
      const analysisSegmentMs =
        recordingData.analysisData?.segmentDurationMs && recordingData.analysisData.segmentDurationMs > 0
          ? recordingData.analysisData.segmentDurationMs
          : ANALYSIS_SEGMENT_MS;
      const headDropCount = headTrimmedMs > 0 ? Math.round(headTrimmedMs / analysisSegmentMs) : 0;
      const dataPoints = (recordingData.analysisData?.dataPoints ?? []).slice(headDropCount);
      // Same start guard the live tape applies — the switch-on transient must not
      // survive into the card and reel waveforms either.
      const levelsAsDb = softenStartLevels(
        dataPoints.map((p) =>
          Number.isFinite(p.dB) ? p.dB : p.amplitude > 0 ? 20 * Math.log10(p.amplitude) : -60
        )
      );
      const capturePeaks = levelsAsDb.length
        ? metersToWaveformPeaks(levelsAsDb, MANAGED_WAVEFORM_PEAK_COUNT)
        : null;
      // The recorder already measured this take (levels + length), so the save only
      // copies the file. Re-decoding it here queued the save behind every background
      // waveform job and then threw the result away (2026-09-21). With no capture
      // analysis, decode now — the user is waiting, so it must not idle-gate.
      const clipId = `clip-${Date.now()}`;
      const managedAudio = await timedStep(
        "save.importAsset",
        importRecordedAudioAsset(
          sourceAudioUri,
          clipId,
          capturePeaks ? { lightweight: true } : { decodeMode: "interactive" }
        ),
        {
          timeoutMs: 30_000,
          // Nobody is waiting for this copy any more — the take recovers from the
          // recorder temp file, so a late managed copy would only be an orphan.
          onLateResult: (late) => void deleteManagedAudioUris([late.audioUri]).catch(() => {}),
        }
      );
      managedAudioUriToCleanup = managedAudio.audioUri;

      const waveformPeaks = capturePeaks ?? managedAudio.waveformPeaks;

      // Persist the high-res detail sidecar from the SAME capture data, so the
      // editor/player reels read it directly instead of re-decoding the saved m4a
      // (which produced a squished/low-detail waveform). Keyed to the managed audio
      // path the clip will reference.
      if (levelsAsDb.length) {
        // Derived data: a slow disk must not hold the save. The reel rebuilds a missing sidecar.
        await timedStep(
          "save.sidecar",
          writeWaveformSidecar(managedAudio.audioUri, metersToWaveformPeaks(levelsAsDb, WAVEFORM_DETAIL_BINS)),
          { timeoutMs: 5_000 }
        ).catch(() => {});
      }

      const attached = await timedStep("save.attach", async () => onRecorded({
        audioUri: managedAudio.audioUri,
        durationMs:
          managedAudio.durationMs ??
          (recordingData.durationMs != null
            ? Math.max(0, recordingData.durationMs - headTrimmedMs)
            : undefined),
        waveformPeaks,
        headTrimmedMs,
        onsetEnvelope: finishOnsetEnvelope(capturedOnsetState, headTrimmedMs),
      }));

      if (attached === false) {
        // The take could not be attached (e.g. its project was removed mid-recording).
        // Preserve the recording rather than silently orphaning it: keep the recorder temp
        // file AND the pending-session marker so the next launch salvages it into the Inbox.
        // Drop only the redundant managed copy.
        if (managedAudioUriToCleanup) {
          await deleteManagedAudioUris([managedAudioUriToCleanup]).catch(() => {});
          managedAudioUriToCleanup = null;
        }
        unrecoveredTakeThisSession = true;
        AppAlert.info(t("recording.keptForRecoveryTitle"), t("recording.keptAttachBody"));
        return false;
      }

      managedAudioUriToCleanup = null;

      // The take is attached in memory. Make it durable NOW rather than trusting the
      // passive debounce — a session whose writes had silently stopped landing lost a
      // take, its title, and its sketch this way (2026-09-07). If the flush is refused
      // or fails, journal the attachment so the next launch re-attaches it instead of
      // showing a dead 0:00 idea.
      let durable = false;
      try {
        await timedStep("save.flush", flushPersistedSnapshot());
        durable = true;
        persistLog("recording.attached");
      } catch (flushError) {
        persistLog("recording.flushFailed", describeError(flushError));
        const located = findClipByAudioUri(managedAudio.audioUri);
        if (located) {
          await persistAttachedRecordingJournal({
            ideaId: located.ideaId,
            clipId: located.clip.id,
            audioUri: managedAudio.audioUri,
            ideaTitle: located.ideaTitle,
            ideaTitleAutoGenerated: located.ideaTitleAutoGenerated,
            clipTitle: located.clip.title,
            durationMs: located.clip.durationMs,
            waveformPeaks: located.clip.waveformPeaks,
            createdAt: located.clip.createdAt,
          }).catch(() => {});
        }
      }

      if (recordingData.fileUri && recordingData.fileUri !== managedAudio.audioUri) {
        // The managed import succeeded, so the recorder temp output is now redundant and should
        // be removed instead of silently accumulating across saves.
        // Housekeeping never holds the save sheet open.
        void FileSystem.deleteAsync(recordingData.fileUri, { idempotent: true }).catch(() => {});
      }
      if (trimTempUriToCleanup && trimTempUriToCleanup !== managedAudio.audioUri) {
        void FileSystem.deleteAsync(trimTempUriToCleanup, { idempotent: true }).catch(() => {});
        trimTempUriToCleanup = null;
      }
      // The marker now either is gone (durable) or points at the managed file (journal).
      if (durable) await clearPendingRecordingSession();
      return true;
    } catch {
      take.facts.expectedStop = false;
      // Roll back the PARTIAL artifacts (the managed copy and the intermediate trim temp),
      // but PRESERVE the recorder temp file AND the pending-session marker — together they
      // are the recoverable take that recoverPendingRecordingSession restores on next
      // launch. Deleting the recorder temp here (as this used to) turned the marker into a
      // dangling pointer and lost the take whenever a step AFTER the managed import failed
      // (sidecar/attach) or on a disk-full save. clearPendingRecordingSession is NOT called,
      // so the marker survives.
      if (managedAudioUriToCleanup) {
        await deleteManagedAudioUris([managedAudioUriToCleanup]).catch(() => {});
      }
      if (trimTempUriToCleanup) {
        await FileSystem.deleteAsync(trimTempUriToCleanup, { idempotent: true }).catch(() => {});
      }
      unrecoveredTakeThisSession = true;
      AppAlert.info(t("recording.keptForRecoveryTitle"), t("recording.keptSaveBody"));
      return false;
    } finally {
      await releaseRecordingAudioSession().catch((error) => {
        console.warn("Recording audio session release after save failed", error);
      });
    }
  }

  /**
   * Throw the take away. Only the native stop is awaited (the screen's state
   * follows it); deleting the file, clearing the recovery marker and releasing
   * the session continue in the background, so Discard and Redo answer at once
   * (2026-10-17).
   */
  async function discardRecording() {
    let fileUri: string | undefined;
    try {
      take.facts.expectedStop = true;
      const recordingData = await timedStep("stopRecording", recorder.stopRecording(), {
        timeoutMs: 15_000,
        // The user threw this take away; if the stop lands late, finish the job.
        onLateResult: (late) => {
          if (late?.fileUri) void FileSystem.deleteAsync(late.fileUri, { idempotent: true }).catch(() => {});
        },
      });
      fileUri = recordingData?.fileUri;
    } catch {
      take.facts.expectedStop = false;
    }
    take.facts.prepared = false;
    prewarmedRef.current = false;
    take.facts.recordingStartedAt = null;
    abortHeadTrim();
    resetLiveWaveform();
    resetOnsetEnvelope();
    discardCleanup = discardCleanup.then(async () => {
      if (fileUri) {
        // Discard should clean up the recorder output because the app never imports it into
        // managed storage or stores metadata for later recovery.
        await FileSystem.deleteAsync(fileUri, { idempotent: true }).catch(() => {});
      }
      // A discarded take must not come back as "recovered" on the next launch.
      await clearPendingRecordingSession().catch(() => {});
      await releaseRecordingAudioSession().catch((error) => {
        console.warn("Recording audio session release after discard failed", error);
      });
    });
  }

  return {
    isRecording: recorder.isRecording,
    isPaused: recorder.isPaused,
    // Record-through takes: the pre-roll head isn't part of the take, so elapsed reads 0
    // during the count-in and the head is subtracted once measured. Downstream consumers
    // (display clock, overdub auto-stop threshold) then need no head awareness.
    elapsedMs: headTrim.pending ? 0 : Math.max(0, displayElapsedMs - headTrim.ms),
    /** The pre-roll the save will cut (0 while unknown): capture ms minus this is take ms. */
    headTrimMs: headTrim.pending ? 0 : headTrim.ms,
    readElapsedMs,
    lastInterruptionReason,
    interruptionToken,
    prepareRecording,
    prewarmRecording,
    releasePrewarm,
    warmInput,
    prewarmState,
    startRecording,
    startPreparedRecording,
    cancelPreparedRecording,
    pauseRecording,
    resumeRecording,
    saveRecording,
    discardRecording,
    /** Re-activate the recording audio session without resuming capture. The metronome's
     *  engine plays into this session with manageAudioSession:false, so on resume it has to
     *  be live BEFORE the click starts — starting the click first is why it failed outright
     *  on iOS after a pause. */
    claimAudioSession: claimRecordingAudioSession,
    /** Raw captured audio in ms — the same axis the beat grid is stamped in, and frozen
     *  while paused, which is what makes it the right thing to phase a resumed click to. */
    getCaptureDurationMs: () => take.liveWaveform.get().durationMs,
    armHeadTrim,
    commitHeadTrim,
    abortHeadTrim,
    getCaptureStartEpochMs,
  };
}
