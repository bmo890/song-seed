import { planSketchTakeRenames } from "../sketchTakeRenames";
import type { ClipVersion } from "../../types";

const take = (id: string, title: string, extra: Partial<ClipVersion> = {}): ClipVersion => ({
  id,
  title,
  notes: "",
  createdAt: 1,
  isPrimary: false,
  ...extra,
});

const plan = (clips: ClipVersion[], from: string, to: string) =>
  planSketchTakeRenames(clips, from, to).map((r) => [r.clip.id, r.nextTitle]);

describe("planSketchTakeRenames", () => {
  it("the founder's case: a received take named the old sketch name plus .wav", () => {
    expect(plan([take("a", "To Create (D Song).wav")], "To Create (D Song).wav", "To Create (D Song)")).toEqual([
      ["a", "To Create (D Song)"],
    ]);
  });

  it("a take named exactly the old name, or the old name plus an extension, follows", () => {
    expect(plan([take("a", "Old"), take("b", "Old.m4a")], "Old", "New")).toEqual([
      ["a", "New"],
      ["b", "New"],
    ]);
  });

  it("a version thread renames in step and keeps each suffix", () => {
    const thread = [take("r", "Old"), take("v2", "Old v2", { parentClipId: "r" }), take("v3", "Old v3", { parentClipId: "v2" })];
    expect(plan(thread, "Old", "New")).toEqual([
      ["r", "New"],
      ["v2", "New v2"],
      ["v3", "New v3"],
    ]);
  });

  it("takes named on purpose are never touched", () => {
    const takes = [take("a", "Bridge riff"), take("b", "Old take"), take("c", "Older"), take("d", "Old v2 alt")];
    expect(plan(takes, "Old", "New")).toEqual([]);
  });

  it("machine-named takes are never touched, even when the old name was machine-named", () => {
    expect(plan([take("a", "New Recording 7")], "New Recording 7", "Love song")).toEqual([]);
    expect(plan([take("b", "Idea 3")], "Idea 3", "Love song")).toEqual([]);
  });

  it("no prompt when nothing changed, the new name is empty, or the take already matches", () => {
    expect(plan([take("a", "Old")], "Old", "Old")).toEqual([]);
    expect(plan([take("a", "Old")], "Old", "  ")).toEqual([]);
    expect(plan([take("a", "New")], "Old", "New")).toEqual([]);
  });

  it("a take whose chosen name IS the old sketch name still follows", () => {
    // isTitleAutoGenerated === false marks a name someone typed; matching the
    // old sketch name exactly still makes it the copy.
    expect(plan([take("a", "Old", { isTitleAutoGenerated: false })], "Old", "New")).toEqual([["a", "New"]]);
  });
});
