import type { SongIdea, Workspace } from "../types";

/**
 * "Make sketch" on a clip turns the idea into a draft sketch in place. Discarding
 * that draft — or finding it stranded on launch — turns it back into the clip it
 * was: same id, same title, same activity, the sketch-only parts dropped.
 *
 * EVERY clip comes back: the clip's older versions, and anything recorded into the
 * draft while it was open. Keeping only the first dropped the rest from the library
 * with their files orphaned (data-safety audit 03-#4; CLAUDE.md data law: never drop
 * versions a person didn't choose to drop). Lineage stays as it was; the primary is
 * the one that was primary before the conversion.
 */
export function revertDraftToClipIdea(idea: SongIdea): SongIdea {
  const primaryId = idea.clips.some((clip) => clip.id === idea.draftClipPrimaryId)
    ? idea.draftClipPrimaryId
    : idea.clips[0]?.id;
  const clipIds = new Set(idea.clips.map((clip) => clip.id));
  const clips = idea.clips.map((clip) => ({
    ...clip,
    isPrimary: clip.id === primaryId,
    // A parent that is not in the stack would leave a dangling thread.
    parentClipId: clip.parentClipId && clipIds.has(clip.parentClipId) ? clip.parentClipId : undefined,
  }));
  return {
    id: idea.id,
    title: idea.title,
    notes: idea.notes,
    status: "clip",
    completionPct: 0,
    kind: "clip",
    collectionId: idea.collectionId,
    clips,
    isTitleAutoGenerated: idea.isTitleAutoGenerated,
    createdAt: idea.createdAt,
    importedAt: idea.importedAt,
    sourceCreatedAt: idea.sourceCreatedAt,
    lastActivityAt: idea.lastActivityAt,
    isBookmarked: idea.isBookmarked,
  };
}

/**
 * A draft sketch is hidden from the collection until its edit sheet is saved
 * or discarded. Killed mid-edit, it stayed a draft forever — and the clips
 * gathered into it were "gone" (2026-10-04). On launch nothing is being
 * edited, so a leftover draft with clips becomes a real sketch under its
 * placeholder name, an empty one is removed, and one that was a clip being
 * grown goes back to being that clip. Untouched workspaces keep their identity.
 */
export function recoverStrandedDraftIdeas(workspaces: Workspace[]) {
  let recovered = 0;
  let removed = 0;
  const next = workspaces.map((workspace) => {
    if (!workspace.ideas.some((idea) => idea.isDraft)) return workspace;
    return {
      ...workspace,
      ideas: workspace.ideas
        .filter((idea) => {
          if (idea.isDraft && idea.clips.length === 0) {
            removed += 1;
            return false;
          }
          return true;
        })
        .map((idea) => {
          if (!idea.isDraft) return idea;
          recovered += 1;
          if (idea.draftFromClipIdea) return revertDraftToClipIdea(idea);
          return { ...idea, isDraft: false };
        }),
    };
  });
  return { workspaces: recovered === 0 && removed === 0 ? workspaces : next, recovered, removed };
}
