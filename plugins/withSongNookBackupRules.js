const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");

/**
 * Android Auto Backup, scoped on purpose (audit 2026-11-02 G5).
 *
 * Expo's default is `allowBackup="true"` with no rules: Google's cloud backup then tries
 * to copy the whole app (audio included), gives up past its 25 MB cap, and keeps the
 * last copy that fit, from the library's first days. A new phone restored from it gets
 * a tiny, stale library that looks like everything came back.
 *
 * - Cloud backup (Google Drive) carries NOTHING. A library database without its audio
 *   would restore titles whose takes have no sound, and a later Merge restore keeps the
 *   silent copies (the current phone wins). SongNook's own backup is the cloud copy.
 * - Device-to-device transfer (Android 12+, cable or Wi-Fi, no size cap) carries the
 *   whole library, audio included, minus temp files and the trash.
 * - Android 11 and older only read `fullBackupContent`, which cannot tell the two
 *   apart, so it carries nothing either; those phones move by SongNook's backup.
 *
 * Lives in the Expo config so every prebuild keeps it.
 */
const FULL_BACKUP_CONTENT = "songnook_backup_rules";
const DATA_EXTRACTION_RULES = "songnook_data_extraction_rules";

const ALL_DOMAINS = ["root", "file", "database", "sharedpref", "external"];

/** App-private folders that are temporary or already-deleted, never worth moving. */
const TRANSIENT_FILE_PATHS = ["songnook/backup-tmp/", "songnook/share/", "songnook/trash/"];

function excludeEverything(indent) {
  return ALL_DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" path="." />`).join("\n");
}

function fullBackupContentXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by plugins/withSongNookBackupRules.js. Android 11 and older: no Auto Backup. -->",
    "<full-backup-content>",
    excludeEverything("  "),
    "</full-backup-content>",
    "",
  ].join("\n");
}

function dataExtractionRulesXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by plugins/withSongNookBackupRules.js. Android 12+: nothing to the cloud,",
    "     the whole library on a device-to-device transfer. -->",
    "<data-extraction-rules>",
    "  <cloud-backup>",
    excludeEverything("    "),
    "  </cloud-backup>",
    "  <device-transfer>",
    ...TRANSIENT_FILE_PATHS.map((p) => `    <exclude domain="file" path="${p}" />`),
    "  </device-transfer>",
    "</data-extraction-rules>",
    "",
  ].join("\n");
}

function applyBackupAttributes(manifest) {
  const application = manifest.manifest.application?.[0];
  if (!application) {
    throw new Error("SongNook backup rules: AndroidManifest has no <application>.");
  }
  application.$ = {
    ...application.$,
    "android:allowBackup": "true",
    "android:fullBackupContent": `@xml/${FULL_BACKUP_CONTENT}`,
    "android:dataExtractionRules": `@xml/${DATA_EXTRACTION_RULES}`,
  };
  return manifest;
}

function withSongNookBackupRules(config) {
  config = withAndroidManifest(config, (mod) => {
    mod.modResults = applyBackupAttributes(mod.modResults);
    return mod;
  });
  return withDangerousMod(config, [
    "android",
    async (mod) => {
      const xmlDir = path.join(mod.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${FULL_BACKUP_CONTENT}.xml`), fullBackupContentXml());
      fs.writeFileSync(path.join(xmlDir, `${DATA_EXTRACTION_RULES}.xml`), dataExtractionRulesXml());
      return mod;
    },
  ]);
}

module.exports = withSongNookBackupRules;
module.exports.applyBackupAttributes = applyBackupAttributes;
module.exports.fullBackupContentXml = fullBackupContentXml;
module.exports.dataExtractionRulesXml = dataExtractionRulesXml;
