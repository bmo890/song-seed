// The recurring words a native musician checks (founder, 2026-11-24: "it's about the
// words, not the grammar ... am I using the right word for input, for chart, for layer").
// One entry per word. `en` is how the app says it in English; `labels` are other exact
// English labels that carry the same word (used to find its current Hebrew); `meaning`
// tells the reviewer what it is in SongNook when the English alone is ambiguous.
// `ex` names the catalog line to show as the example when the automatic pick takes the
// wrong sense of the word ("level" of a folder, "part" of the library).
// `keys` pins the exact catalog lines for a word whose English is ambiguous ("key", "band",
// "Close"): the first gives its current Hebrew; later short labels are listed as other
// Hebrew the app uses for it; a later sentence is its example. `he` overrides the
// current Hebrew when the first line carries more than the bare word.
// `seen` overrides where the word is shown, when a shared Hebrew line names the wrong page.
// Every pinned line and example must be one the app really shows (terms.mjs checks it
// against the full sheet; screen-reader-only lines don't count).

